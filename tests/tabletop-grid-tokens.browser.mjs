import assert from 'node:assert/strict';
import {tabletopFixture} from './helpers/tabletop-fixture.mjs';
import {DEFAULT_GRID,LOCAL_GM} from '../src/web/tabletop.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{}),args:JSON.parse(process.env.CHROMIUM_ARGS||'["--no-sandbox"]')});
const f=await tabletopFixture({server:true});
try {
  const session=await f.store.createSession(LOCAL_GM,'Размер клетки');
  const location=await f.store.createLocation(session.id,LOCAL_GM,'Поле');
  await f.store.updateScene(location.scene_id,LOCAL_GM,{revision:1,name:'Поле',grid:{...DEFAULT_GRID,cellSize:150}});
  const {token}=await f.store.tokens.add(location.scene_id,LOCAL_GM,{kind:'npc',name:'Страж',x:450,y:450,scene_revision:2,snap:true});
  const context=await browser.newContext({viewport:{width:1512,height:1120}});
  await context.addInitScript(()=>{localStorage.setItem('dnd-theme','tavern');localStorage.setItem('dnd-lang','ru');});
  const page=await context.newPage();page.on('dialog',d=>d.accept());
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(f.origin+'/tabletop/'+session.id);
  const idle=()=>page.waitForFunction(()=>!document.querySelector('[data-vtt-root]').hasAttribute('aria-busy'));
  const current=async()=>(await f.store.tokens.list(location.scene_id,LOCAL_GM))[0];
  for(const size of [150,50,70,100,149,151,200,37.5,25,5,500]) {
    await page.locator('[data-inspector-tab=map]').click();
    await page.locator('[name=cellSize]').fill(String(size));
    if(await page.locator('[data-vtt-save]').isEnabled()){await page.locator('[data-vtt-save]').click();await idle();}
    const before=await current();
    const node=page.locator(`[data-token-id="${token.id}"]`);
    const scale=await page.locator('[data-vtt-map]').evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).a);
    const box=await node.boundingBox();assert.ok(Math.abs(box.width-size*scale)<.1,`width ${box.width} versus ${size*scale}`);
    await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
    await page.mouse.move(box.x+box.width/2+Math.max(8,size*scale),box.y+box.height/2,{steps:5});await page.mouse.up();await idle();
    const moved=await current();assert.ok(moved.x>before.x,`drag at ${size}: ${before.x} -> ${moved.x}`);
    assert.ok(Math.abs(moved.x/size-Math.round(moved.x/size))<.001);
    console.log('PASS saved grid '+size+'px: rendered size, pointer drag and snap');
  }
  await page.locator('[data-inspector-tab=map]').click();await page.locator('[name=cellSize]').fill('150');
  await page.locator('[data-vtt-save]').click();await idle();
  await page.locator('[name=cellSize]').fill('70');await page.locator('[data-inspector-tab=tokens]').click();
  const before=await current();await page.locator(`[data-token-id="${token.id}"]`).press('ArrowRight');await idle();
  assert.notEqual((await current()).x,before.x);
  assert.equal((await f.store.scene(location.scene_id,LOCAL_GM)).grid.cellSize,70);
  assert.equal((await current()).x%70,0);
  assert.equal(await page.locator('[data-vtt-grid-pending]').isVisible(),false);
  console.log('PASS 150 → 70: token action saves the edited grid and moves using its new cells');
  await page.locator('[data-inspector-tab=map]').click();await page.locator('[name=cellSize]').fill('90');
  await page.locator('[data-inspector-tab=tokens]').click();
  const original=await current();
  await page.route('**/api/tabletop/scenes/'+location.scene_id,route=>route.abort());
  await page.locator(`[data-token-id="${token.id}"]`).press('ArrowLeft');await idle();
  assert.equal((await current()).revision,original.revision);
  assert.equal((await f.store.scene(location.scene_id,LOCAL_GM)).grid.cellSize,70);
  assert.equal(await page.locator(`[data-token-id="${token.id}"]`).evaluate(el=>parseFloat(el.style.left)),original.x);
  assert.equal(await page.locator('[data-vtt-grid-pending]').isVisible(),true);
  assert.match(await page.locator('[data-vtt-status]').textContent(),/Не удалось связаться/);
  await page.unroute('**/api/tabletop/scenes/'+location.scene_id);
  await page.locator(`[data-token-id="${token.id}"]`).press('ArrowLeft');await idle();
  assert.equal((await f.store.scene(location.scene_id,LOCAL_GM)).grid.cellSize,90);
  assert.equal((await current()).x%90,0);
  console.log('PASS failed grid save preserves the token and allows retry');
  await page.locator('[data-inspector-tab=map]').click();await page.locator('[name=cellSize]').fill('0');
  await page.locator('[data-inspector-tab=tokens]').click();
  const valid=await current();await page.locator(`[data-token-id="${token.id}"]`).press('ArrowLeft');await idle();
  assert.equal((await current()).revision,valid.revision);
  assert.equal(await page.locator('[data-vtt-settings]').isVisible(),true);
  assert.match(await page.locator('[data-vtt-status]').textContent(),/Проверьте настройки/);
  console.log('PASS invalid grid opens its settings and does not mutate the token');
  await page.locator('[name=cellSize]').fill('75');await page.locator('[data-inspector-tab=tokens]').click();
  await page.locator('[data-token-add] [name=kind]').selectOption('npc');
  await page.locator('[data-token-add] [name=name]').fill('Подкрепление');await page.locator('[data-token-add] button').click();await idle();
  assert.equal((await f.store.scene(location.scene_id,LOCAL_GM)).grid.cellSize,75);
  assert.equal((await f.store.tokens.list(location.scene_id,LOCAL_GM)).length,2);
  await page.reload();assert.equal(await page.locator('[name=cellSize]').inputValue(),'75');
  assert.equal(await page.locator('[data-token-id]').count(),2);
  console.log('PASS adding a token saves the new grid and both survive reload');
  const edge=await current(),scene=await f.store.scene(location.scene_id,LOCAL_GM);
  await f.store.tokens.change(edge.id,LOCAL_GM,{x:1925,y:0,snap:false,revision:edge.revision,scene_revision:scene.revision},'move');
  await page.reload();await page.locator('[name=cellSize]').fill('500');
  await page.locator(`[data-token-id="${edge.id}"]`).press('ArrowLeft');await idle();
  const clamped=await current();assert.equal(clamped.x,1500);assert.equal(clamped.revision,edge.revision+3);
  console.log('PASS grid enlargement clamps at the map edge and uses the refreshed token revision');
  const changed=await f.store.scene(location.scene_id,LOCAL_GM);
  await f.store.updateScene(location.scene_id,LOCAL_GM,{revision:changed.revision,name:changed.location_name,grid:{...changed.grid,cellSize:100}});
  await page.locator('[data-inspector-tab=map]').click();await page.locator('[name=cellSize]').fill('70');
  const fresh=await current();await page.locator(`[data-token-id="${edge.id}"]`).press('ArrowLeft');await idle();
  assert.equal((await current()).revision,fresh.revision);
  assert.match(await page.locator('[data-vtt-status]').textContent(),/другой вкладке/);
  console.log('PASS a conflicting grid blocks the queued move without overwriting another tab');
  assert.deepEqual(errors,[]);
} finally {await browser.close();await f.close();}
